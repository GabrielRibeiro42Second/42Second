----------------------------------------------------------
-- Workspace Model
--
-- Representa todas as informações conhecidas sobre
-- um projeto.
----------------------------------------------------------

local Workspace = {}

function Workspace.new()
  local workspace = {

    --------------------------------------------------
    -- Informações básicas
    --------------------------------------------------

    name = nil,
    path = nil,

    --------------------------------------------------
    -- Linguagem
    --------------------------------------------------

    language = nil,

    --------------------------------------------------
    -- Build
    --------------------------------------------------

    build_system = nil,

    --------------------------------------------------
    -- Ferramentas
    --------------------------------------------------

    git = false,
    docker = false,

    --------------------------------------------------
    -- Arquivos
    --------------------------------------------------

    readme = false,

    --------------------------------------------------
    -- Futuro
    --------------------------------------------------

    plugins = {},

    layout = nil

  }

  return workspace
end

return Workspace
